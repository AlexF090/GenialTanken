/**
 * Generates the `.htaccess` for the static web app on Hetzner Webhosting (Apache with
 * mod_rewrite, mod_alias, mod_headers and mod_deflate). `generate-hosting-files.ts` writes it
 * into the build output; the next deploy overwrites whatever is on the server.
 */

export interface HtaccessOptions {
  /** Origin the web app is served from, without trailing slash. */
  webOrigin: string;
  /** Origin of the API the app calls directly (`connect-src`). */
  apiOrigin: string;
  /** The legal notice of appool.de, which applies to every subdomain. */
  legalNoticeUrl: string;
  /** CSP sources (`'sha256-…'`) of the inline scripts of `index.html`. */
  inlineScriptHashes: readonly string[];
}

const ONE_YEAR_IN_SECONDS = 31_536_000;
const ONE_DAY_IN_SECONDS = 86_400;

const IMMUTABLE_CACHE_CONTROL = `public, max-age=${String(ONE_YEAR_IN_SECONDS)}, immutable`;
const SHORT_CACHE_CONTROL = `public, max-age=${String(ONE_DAY_IN_SECONDS)}`;
const REVALIDATE_CACHE_CONTROL = 'no-cache';
const HTML_PATTERN = '^text/html(;|$)';

/**
 * Two years, with subdomains. Deliberately without `preload`: an entry in the preload lists is
 * hard to undo and would bind every subdomain of appool.de.
 */
const STRICT_TRANSPORT_SECURITY = 'max-age=63072000; includeSubDomains';

/**
 * Scripts and styles at the root with the content hash Angular puts in their names
 * (`outputHashing: all`), e.g. `main-PLGJPCCY.js`, `chunk-_Jdiwry7.js`, `styles-T2X3EKHF.css`.
 * The service worker scripts (`ngsw-worker.js`, `safety-worker.js`) have no hash of that shape.
 */
export const CACHE_BUSTED_FILE_PATTERN = '^/[^/]+-[A-Za-z0-9_]{8}\\.(js|css)$';

/**
 * Files that decide which app version runs: the page that names the hashed files, the service
 * worker with its safety variants and manifest, and the web manifest. They keep their names, so
 * the browser must ask again on every request, or a service worker would stay a year.
 */
export const REVALIDATED_FILE_PATTERN =
  '^(index\\.html|ngsw\\.json|ngsw-worker\\.js|safety-worker\\.js|worker-basic\\.min\\.js|manifest\\.webmanifest)$';

const COMPRESSIBLE_MIME_TYPES = [
  'text/html',
  'text/css',
  'text/plain',
  'text/xml',
  'application/javascript',
  'text/javascript',
  'application/json',
  'application/manifest+json',
  'image/svg+xml',
];

const escapeForRegularExpression = (value: string): string =>
  value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * As strict as the app allows:
 *
 * - Scripts only from the own origin plus the inline scripts of `index.html`, by hash. No
 *   `unsafe-inline` or `unsafe-eval`.
 * - `style-src` needs `'unsafe-inline'`: Angular adds the styles of its components as `<style>`
 *   elements at run time. A static host can neither send a nonce for them nor know their hashes
 *   at build time. A hash in `style-src` would not help either: with CSP level 3 a hash or nonce
 *   makes browsers ignore `'unsafe-inline'`, which would block exactly these styles. So
 *   `style-src` has no hashes. The risk stays small because scripts remain locked down.
 * - Map tiles come from OpenStreetMap (default) and Mapbox (production token) as images.
 * - The app talks to itself (service worker, manifest) and to the API only.
 */
export const buildContentSecurityPolicy = ({
  apiOrigin,
  inlineScriptHashes,
}: HtaccessOptions): string =>
  [
    "default-src 'self'",
    ["script-src 'self'", ...inlineScriptHashes].join(' '),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: https://tile.openstreetmap.org https://api.mapbox.com",
    "font-src 'self'",
    `connect-src 'self' ${apiOrigin}`,
    "worker-src 'self'",
    "manifest-src 'self'",
    "frame-ancestors 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "object-src 'none'",
  ].join('; ');

export const buildHtaccess = (options: HtaccessOptions): string => {
  const host = new URL(options.webOrigin).host;
  const securityHeaders: Readonly<Record<string, string>> = {
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'X-XSS-Protection': '0',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'Cross-Origin-Opener-Policy': 'same-origin',
    // The app asks for the position of the device itself.
    'Permissions-Policy': 'geolocation=(self), camera=(), microphone=()',
    'Content-Security-Policy': buildContentSecurityPolicy(options),
    // Set unconditionally: on Hetzner Webhosting the mod_headers condition
    // `expr=%{HTTPS} == 'on'` did not match HTTPS answers. Browsers ignore the header over HTTP.
    'Strict-Transport-Security': STRICT_TRANSPORT_SECURITY,
  };

  return [
    `# Generated by \`pnpm --filter web build\` (apps/web/hosting/htaccess.ts) for ${host}.`,
    '# Do not edit on the server; the next deploy overwrites the file.',
    '',
    'Options -Indexes',
    '# Missing files get the app (with status 404); the rewrite below serves it for client routes.',
    'ErrorDocument 404 /index.html',
    'AddType application/manifest+json .webmanifest',
    '',
    'RewriteEngine On',
    '',
    '# HTTP to HTTPS on the same host. The target carries the fixed address, never the raw host header.',
    'RewriteCond %{HTTPS} !=on',
    `RewriteCond %{HTTP_HOST} ^${escapeForRegularExpression(host)}$ [NC]`,
    `RewriteRule ^ ${options.webOrigin}%{REQUEST_URI} [R=301,L,NE]`,
    '',
    '# The legal notice lives on appool.de and applies to every subdomain.',
    `Redirect 301 /impressum ${options.legalNoticeUrl}`,
    '',
    '# Client routes (/favorites, /stations/fr-1, /datenschutz) get index.html. Real files and',
    '# directories are served as they are; a missing file with an extension is a 404.',
    'RewriteCond %{REQUEST_FILENAME} !-f',
    'RewriteCond %{REQUEST_FILENAME} !-d',
    'RewriteCond %{REQUEST_URI} !\\.[A-Za-z0-9]+$',
    'RewriteRule ^ /index.html [L]',
    '',
    '# Compress text answers.',
    '<IfModule mod_deflate.c>',
    `  AddOutputFilterByType DEFLATE ${COMPRESSIBLE_MIME_TYPES.join(' ')}`,
    '</IfModule>',
    '',
    '<IfModule mod_headers.c>',
    ...Object.entries(securityHeaders).map(
      ([name, value]) => `  Header always set ${name} "${value}"`
    ),
    '',
    '  # Files with a content hash in their name never change.',
    `  <If "%{REQUEST_URI} =~ m#${CACHE_BUSTED_FILE_PATTERN}#">`,
    `    Header set Cache-Control "${IMMUTABLE_CACHE_CONTROL}"`,
    '  </If>',
    '  <If "%{REQUEST_URI} =~ m#^/media/#">',
    `    Header set Cache-Control "${IMMUTABLE_CACHE_CONTROL}"`,
    '  </If>',
    '',
    '  # Icons keep their names, so they may only be cached briefly.',
    '  <If "%{REQUEST_URI} =~ m#^/icons/#">',
    `    Header set Cache-Control "${SHORT_CACHE_CONTROL}"`,
    '  </If>',
    '',
    '  # The files that decide which version runs are checked on every request (usually a 304).',
    `  <FilesMatch "${REVALIDATED_FILE_PATTERN}">`,
    `    Header always set Cache-Control "${REVALIDATE_CACHE_CONTROL}"`,
    '  </FilesMatch>',
    '',
    '  # Every route and the 404 page are index.html, whatever the requested path was. The',
    '  # condition sits on the header itself, because <If> runs before the content type is known.',
    `  Header always set Cache-Control "${REVALIDATE_CACHE_CONTROL}" "expr=%{CONTENT_TYPE} =~ m#${HTML_PATTERN}#"`,
    '</IfModule>',
    '',
  ].join('\n');
};
